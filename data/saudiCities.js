const norm = (s) =>
  String(s || "")
    .trim()
    .toLowerCase()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/^(al|el|ad|ar|as|az|an|at)[\s-]/, "")
    .replace(/^ال/, "")
    .replace(/['’\s-]/g, "");

/** Region key for a typed / picked city name (English or Arabic), or "" if unknown. */
export function regionForCity(city) {
  const n = norm(city);
  if (!n) return "";
  const hit = SAUDI_CITIES.find((c) => norm(c.en) === n || norm(c.ar) === n);
  if (hit) return hit.region;
  // Lookup results sometimes return the region name itself (e.g. "Riyadh")
  const reg = SAUDI_REGIONS.find((r) => norm(r.key) === n || norm(r.en) === n || norm(r.ar) === n);
  return reg ? reg.key : "";
}
